-- =====================================================================
-- 01 SETUP: warehouse, database, schemas, roles
-- =====================================================================

-- Lets Cortex use models hosted in other regions (needed for some Claude models)
ALTER ACCOUNT SET CORTEX_ENABLED_CROSS_REGION = 'ANY_REGION';

CREATE WAREHOUSE IF NOT EXISTS {{WAREHOUSE}}
  WAREHOUSE_SIZE = 'MEDIUM' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
USE WAREHOUSE {{WAREHOUSE}};

CREATE DATABASE IF NOT EXISTS {{DATABASE}};
CREATE SCHEMA IF NOT EXISTS {{DATABASE}}.{{ANALYTICS}};
CREATE SCHEMA IF NOT EXISTS {{DATABASE}}.{{SEARCH}};
CREATE SCHEMA IF NOT EXISTS {{DATABASE}}.{{MARTS}};
CREATE SCHEMA IF NOT EXISTS {{DATABASE}}.{{GOVERNANCE}};

-- Roles: engineer > analyst > 3 app personas
CREATE ROLE IF NOT EXISTS {{ENGINEER_ROLE}};
CREATE ROLE IF NOT EXISTS {{ANALYST_ROLE}};
CREATE ROLE IF NOT EXISTS {{EXECUTIVE_ROLE}};
CREATE ROLE IF NOT EXISTS {{CLINICAL_ROLE}};
CREATE ROLE IF NOT EXISTS {{FINANCE_ROLE}};

GRANT ROLE {{ANALYST_ROLE}} TO ROLE {{ENGINEER_ROLE}};
GRANT ROLE {{ANALYST_ROLE}} TO ROLE {{EXECUTIVE_ROLE}};
GRANT ROLE {{ANALYST_ROLE}} TO ROLE {{CLINICAL_ROLE}};
GRANT ROLE {{ANALYST_ROLE}} TO ROLE {{FINANCE_ROLE}};
GRANT ROLE {{ENGINEER_ROLE}} TO ROLE SYSADMIN;
GRANT ROLE {{EXECUTIVE_ROLE}} TO ROLE SYSADMIN;
GRANT ROLE {{CLINICAL_ROLE}} TO ROLE SYSADMIN;
GRANT ROLE {{FINANCE_ROLE}} TO ROLE SYSADMIN;

-- Give every role to you, so you can switch between them in the app
SET my_user = CURRENT_USER();
GRANT ROLE {{ENGINEER_ROLE}} TO USER IDENTIFIER($my_user);
GRANT ROLE {{ANALYST_ROLE}} TO USER IDENTIFIER($my_user);
GRANT ROLE {{EXECUTIVE_ROLE}} TO USER IDENTIFIER($my_user);
GRANT ROLE {{CLINICAL_ROLE}} TO USER IDENTIFIER($my_user);
GRANT ROLE {{FINANCE_ROLE}} TO USER IDENTIFIER($my_user);